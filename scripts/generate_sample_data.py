"""Generate sql/02_sample_data.sql deterministically (fixed RNG seed).

The data is SYNTHETIC. Sector names mimic Islamabad's grid, but the geometry is a
simplified rectangular grid and the facilities/roads are randomly generated.
Run:  python3 scripts/generate_sample_data.py > sql/02_sample_data.sql
"""
import random
from decimal import Decimal as D

random.seed(42)

LON_MAX, LON_STEP = D("73.096"), D("0.022")   # sector 6 is the eastern-most column
LAT_MAX, LAT_STEP = D("33.740"), D("0.020")   # series F is the northern-most row
SERIES = ["F", "G", "H", "I"]
NUMBERS = [6, 7, 8, 9, 10]
EXTENT = (72.986, 33.660, 73.096, 33.740)      # xmin, ymin, xmax, ymax

