#!/usr/bin/env python3
"""Generate sql/02_sample_data.sql deterministically (fixed RNG seed).

The data is SYNTHETIC. Sector names mimic Islamabad's grid, but the geometry is a
simplified rectangular grid and the facilities/roads are randomly generated.
Run:  python3 scripts/generate_sample_data.py > sql/02_sample_data.sql
"""
import random
from decimal import Decimal as D

random.seed(42)

LON_MAX, LON_STEP = D("73.096"), D("0.022")   # sector 6 is the eastern-most column
LAT_MAX, LAT_STEP = D("33.740"), D("0.020")   # series F is the northern-most row
SERIES = ["F", "G", "H", "I"]
NUMBERS = [6, 7, 8, 9, 10]
EXTENT = (72.986, 33.660, 73.096, 33.740)      # xmin, ymin, xmax, ymax

out = ["-- GENERATED by scripts/generate_sample_data.py (seed 42). Do not edit by hand.",
       "-- Synthetic data: illustrative only, not official boundaries.", "",
       "TRUNCATE facilities, roads, sectors RESTART IDENTITY;", ""]

# --- sectors -----------------------------------------------------------------
out.append("INSERT INTO sectors (name, series, geom) VALUES")
rows = []
for r, s in enumerate(SERIES):
    for n in NUMBERS:
        east = LON_MAX - (n - 6) * LON_STEP
        west = east - LON_STEP
        north = LAT_MAX - r * LAT_STEP
        south = north - LAT_STEP
        rows.append(f"  ('{s}-{n}', '{s}', ST_MakeEnvelope({west}, {south}, {east}, {north}, 4326))")
out.append(",\n".join(rows) + ";\n")

# --- facilities --------------------------------------------------------------
types = ["hospital"] * 8 + ["school"] * 20 + ["park"] * 12 + ["market"] * 10 + ["pharmacy"] * 10
random.shuffle(types)
clumps = [(73.060, 33.725), (73.030, 33.705), (73.075, 33.690)]   # dense areas for clustering
xmin, ymin, xmax, ymax = EXTENT
pad = 0.002

def uniform():
    return (random.uniform(xmin + pad, xmax - pad), random.uniform(ymin + pad, ymax - pad))

def clumped(c):
    while True:
        x, y = random.gauss(c[0], 0.0015), random.gauss(c[1], 0.0015)
        if xmin + pad < x < xmax - pad and ymin + pad < y < ymax - pad:
            return x, y

pts = [clumped(clumps[i % 3]) for i in range(30)] + [uniform() for _ in range(30)]
random.shuffle(pts)

counter = {}
out.append("INSERT INTO facilities (name, type, geom) VALUES")
rows = []
for t, (x, y) in zip(types, pts):
    counter[t] = counter.get(t, 0) + 1
    rows.append(f"  ('{t.capitalize()} {counter[t]:02d}', '{t}', ST_SetSRID(ST_MakePoint({x:.5f}, {y:.5f}), 4326))")
out.append(",\n".join(rows) + ";\n")

# --- roads -------------------------------------------------------------------
def wiggle(points):
    return ", ".join(f"{x:.5f} {y + random.uniform(-0.0008, 0.0008):.5f}" for x, y in points)

out.append("INSERT INTO roads (name, geom) VALUES")
rows = []
lats = [LAT_MAX - (i + D("0.5")) * LAT_STEP for i in range(4)]
for name, lat in zip(["Avenue F", "Avenue G", "Avenue H", "Avenue I"], lats):
    xs = [xmin + i * (xmax - xmin) / 4 for i in range(5)]
    wkt = wiggle([(x, float(lat)) for x in xs])
    rows.append(f"  ('{name}', ST_GeomFromText('LINESTRING({wkt})', 4326))")
lons = [LON_MAX - (n - 6 + D("0.5")) * LON_STEP for n in NUMBERS]
for n, lon in zip(NUMBERS, lons):
    ys = [ymin + i * (ymax - ymin) / 4 for i in range(5)]
    pts_ = ", ".join(f"{float(lon) + random.uniform(-0.0008, 0.0008):.5f} {y:.5f}" for y in ys)
    rows.append(f"  ('Street {n}', ST_GeomFromText('LINESTRING({pts_})', 4326))")
rows.append("  ('Expressway', ST_GeomFromText('LINESTRING(72.99000 33.66500, 73.03000 33.69000, 73.06000 33.71500, 73.09000 33.73500)', 4326))")
out.append(",\n".join(rows) + ";\n")
out.append("ANALYZE sectors; ANALYZE facilities; ANALYZE roads;")
print("\n".join(out))
