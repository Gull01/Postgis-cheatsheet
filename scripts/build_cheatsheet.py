#!/usr/bin/env python3
"""Build CHEATSHEET.md and the query table in README.md from queries/*.sql headers.

Header format at the top of each query file:
    -- title: ...        -- category: ...     -- functions: a, b, c
    -- expect_rows: N    -- note: ...
"""
import pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
queries = []
for f in sorted((root / "queries").glob("*.sql")):
    meta, sql_lines = {}, []
    for line in f.read_text().splitlines():
        m = re.match(r"-- (\w+): (.*)", line)
        if m and not sql_lines:          # leading header block
            meta[m.group(1)] = m.group(2).strip()
        else:                            # everything after it is the query
            sql_lines.append(line)
    meta["file"] = f.name
    meta["num"] = int(f.name[:2])
    meta["sql"] = "\n".join(sql_lines).strip()
    queries.append(meta)

# ---- CHEATSHEET.md -----------------------------------------------------------
md = ["# PostGIS cheat sheet", "",
      "20 spatial SQL queries, each tested against the sample dataset in `sql/`.",
      "Generated by `scripts/build_cheatsheet.py`. Edit the files in `queries/`, not this page.", ""]
cats = list(dict.fromkeys(q["category"] for q in queries))
md.append("## Contents\n")
for c in cats:
    md.append(f"- **{c}**: " + ", ".join(f"[{q['num']}](#q{q['num']:02d})" for q in queries if q["category"] == c))
md.append("")
for c in cats:
    md += [f"## {c}", ""]
    for q in (x for x in queries if x["category"] == c):
        md += [f'<a id="q{q["num"]:02d}"></a>', f"### {q['num']}. {q['title']}", "",
               f"`{q['functions']}`  ·  returns **{q['expect_rows']}** rows  ·  [`queries/{q['file']}`](queries/{q['file']})", "",
               "```sql", q["sql"], "```", "", f"> {q['note']}", ""]
(root / "CHEATSHEET.md").write_text("\n".join(md))

# ---- README query table ------------------------------------------------------
rows = ["| # | Query | Key functions |", "|---|-------|---------------|"]
for q in queries:
    rows.append(f"| {q['num']} | [{q['title']}](queries/{q['file']}) | `{q['functions']}` |")
table = "\n".join(rows)
readme = root / "README.md"
if readme.exists():
    text = readme.read_text()
    new = re.sub(r"<!-- QUERIES:START -->.*?<!-- QUERIES:END -->",
                 lambda m: "<!-- QUERIES:START -->\n" + table + "\n<!-- QUERIES:END -->", text, flags=re.S)
    readme.write_text(new)
print(f"Built CHEATSHEET.md with {len(queries)} queries")
